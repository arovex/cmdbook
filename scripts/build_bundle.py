#!/usr/bin/env python3
"""Validate data/*.json and generate data/bundle.js.

Usage:
    python scripts/build_bundle.py          # validate + write bundle
    python scripts/build_bundle.py --check  # validate + fail if bundle is stale (CI)
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
TOPIC_ORDER = ["linux", "git", "python", "security", "web"]
SAFETY = {"safe", "caution", "danger"}

errors = []


def fail(message):
    errors.append(message)


entries = []
for path in sorted(DATA.glob("*.json")):
    if path.name == "commands.json":
        continue

    topic = path.stem
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except Exception as error:  # noqa: BLE001 - report the parse error to the user
        fail(f"{path.name}: invalid JSON — {error}")
        continue

    if not isinstance(data, list):
        fail(f"{path.name}: expected a JSON array of entries")
        continue

    for index, entry in enumerate(data):
        where = f"{path.name}[{index}]"
        if not isinstance(entry, dict):
            fail(f"{where}: expected an object")
            continue

        for key in ("id", "command", "plain", "when"):
            value = entry.get(key)
            if not isinstance(value, str) or not value.strip():
                fail(f'{where}: missing or empty "{key}"')

        if entry.get("safety") not in SAFETY:
            fail(f"{where}: safety must be one of safe, caution, danger")

        tags = entry.get("tags")
        if not isinstance(tags, list) or not tags:
            fail(f"{where}: tags must be a non-empty array")

        flags = entry.get("flags", [])
        if not isinstance(flags, list):
            fail(f"{where}: flags must be an array")
        else:
            for flag_index, flag in enumerate(flags):
                if (
                    not isinstance(flag, dict)
                    or not isinstance(flag.get("flag"), str)
                    or not isinstance(flag.get("meaning"), str)
                ):
                    fail(f'{where}.flags[{flag_index}]: needs string "flag" and "meaning"')

        related = entry.get("related", [])
        if not isinstance(related, list) or not all(isinstance(item, str) for item in related):
            fail(f"{where}: related must be an array of entry ids")

        entries.append({**entry, "topic": topic})

seen = set()
for entry in entries:
    entry_id = entry.get("id")
    if entry_id in seen:
        fail(f"duplicate id: {entry_id}")
    seen.add(entry_id)

for entry in entries:
    for related_id in entry.get("related", []):
        if related_id not in seen:
            fail(f'{entry.get("id")}: related id "{related_id}" does not exist')

commands = {}
commands_path = DATA / "commands.json"
try:
    commands = json.loads(commands_path.read_text(encoding="utf-8"))
    if not isinstance(commands, dict):
        fail("commands.json: expected an object keyed by command name")
        commands = {}
except Exception as error:  # noqa: BLE001
    fail(f"commands.json: invalid JSON — {error}")

for key, value in commands.items():
    if not isinstance(value, dict) or not isinstance(value.get("desc"), str):
        fail(f'commands.json: "{key}" needs a string "desc"')
        continue
    flags = value.get("flags", {})
    if not isinstance(flags, dict) or not all(
        isinstance(name, str) and isinstance(meaning, str) for name, meaning in flags.items()
    ):
        fail(f'commands.json: "{key}" flags must map strings to strings')

if errors:
    print(f"ERROR: {len(errors)} problem(s):", file=sys.stderr)
    for error in errors:
        print(f"  - {error}", file=sys.stderr)
    sys.exit(1)

order = {topic: index for index, topic in enumerate(TOPIC_ORDER)}
entries.sort(key=lambda entry: (order.get(entry["topic"], 99), entry["command"].lower()))

payload = {"entries": entries, "commands": commands}
bundle = (
    "/* Generated by scripts/build_bundle.py — edit the JSON files in data/ instead. */\n"
    "window.CMDBOOK_DATA = "
    + json.dumps(payload, indent=2, ensure_ascii=False)
    + ";\n"
)

out = DATA / "bundle.js"

if "--check" in sys.argv:
    current = out.read_text(encoding="utf-8") if out.exists() else ""
    if current != bundle:
        print(
            "ERROR: data/bundle.js is out of date. Run: python scripts/build_bundle.py",
            file=sys.stderr,
        )
        sys.exit(1)
    print(f"OK: data valid, bundle up to date, {len(entries)} entries")
else:
    out.write_text(bundle, encoding="utf-8", newline="\n")
    topics = len({entry["topic"] for entry in entries})
    print(f"OK: wrote data/bundle.js, {len(entries)} entries, {topics} topics")
